#!/usr/bin/env bash
# issues-reindex.sh — Rebuild .codex/issues/index.md from issue body files.
# Safe recovery after parallel index conflicts. Does not touch body files.
# Usage: issues-reindex.sh [--also-monolith]
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/config.sh"
source "$(dirname "${BASH_SOURCE[0]}")/lib-issues.sh"

ALSO_MONO=0
[[ "${1:-}" == "--also-monolith" ]] && ALSO_MONO=1

ISSUES_DIR="$PROJECT_ISSUES_DIR/issues"
mkdir -p "$ISSUES_DIR/resolved"
INDEX="$ISSUES_DIR/index.md"

export IR_DIR="$ISSUES_DIR" IR_INDEX="$INDEX" IR_MONO="$ALSO_MONO"
export IR_KNOWN="$PROJECT_ISSUES_FILE" IR_RESOLVED="$RESOLVED_FILE"

python3 - <<'PY'
import os, re, pathlib

issues_dir = pathlib.Path(os.environ["IR_DIR"])
index_path = pathlib.Path(os.environ["IR_INDEX"])
also_mono = os.environ.get("IR_MONO") == "1"

def parse_body(text: str):
    title = ""
    fields = {}
    m = re.match(r"^###\s+(\d+)\.\s+(.*)$", text.splitlines()[0] if text else "")
    iid = int(m.group(1)) if m else None
    title = m.group(2).strip() if m else ""
    for line in text.splitlines():
        mm = re.match(r"^- ([A-Za-z][A-Za-z ]*): ?(.*)$", line)
        if mm:
            fields[mm.group(1)] = mm.group(2).strip()
    return iid, title, fields

rows = []
active_bodies = []
resolved_bodies = []

for path in sorted(issues_dir.glob("*.md")):
    if path.name == "index.md":
        continue
    text = path.read_text(encoding="utf-8")
    iid, title, fields = parse_body(text)
    if iid is None:
        continue
    rows.append(
        (
            iid,
            title,
            fields.get("Status", "backlog"),
            fields.get("Type", ""),
            fields.get("Severity", ""),
            fields.get("Priority", ""),
            "active",
        )
    )
    active_bodies.append(text.rstrip() + "\n")

res_dir = issues_dir / "resolved"
if res_dir.is_dir():
    for path in sorted(res_dir.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        iid, title, fields = parse_body(text)
        if iid is None:
            continue
        rows.append(
            (
                iid,
                title,
                "resolved",
                fields.get("Type", ""),
                fields.get("Severity", ""),
                fields.get("Priority", ""),
                "resolved",
            )
        )
        resolved_bodies.append(text.rstrip() + "\n")

rows.sort(key=lambda r: r[0])
lines = [
    "# Issues index",
    "",
    "| id | title | status | type | severity | priority | loc |",
    "|---:|-------|--------|------|----------|----------|-----|",
]
for iid, title, st, typ, sev, prio, loc in rows:
    safe = title.replace("|", "/")
    lines.append(f"| {iid} | {safe} | {st} | {typ} | {sev} | {prio} | {loc} |")
lines.append("")
lines.append("_Regenerated by `issues-reindex.sh`. Bodies are canonical under `issues/`._")
lines.append("")
index_path.write_text("\n".join(lines), encoding="utf-8")
print(index_path)

if also_mono:
    known = pathlib.Path(os.environ["IR_KNOWN"])
    resolved = pathlib.Path(os.environ["IR_RESOLVED"])
    known.write_text(
        "## Known Issues\n\n"
        + ("\n".join(active_bodies) if active_bodies else "")
        + "\n",
        encoding="utf-8",
    )
    resolved.parent.mkdir(parents=True, exist_ok=True)
    resolved.write_text(
        "## Resolved Issues\n\n"
        + ("\n".join(resolved_bodies) if resolved_bodies else "")
        + "\n",
        encoding="utf-8",
    )
    print(known)
    print(resolved)
PY
